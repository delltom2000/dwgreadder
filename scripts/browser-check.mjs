import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||undefined});
const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')console.log('console:',m.text());});
await page.goto('http://127.0.0.1:5173/');
await page.screenshot({path:'.local/welcome.png'});
await page.locator('#sample').click();
await page.waitForFunction(()=>document.querySelector('#welcome').hidden,{},{timeout:90000});
await page.screenshot({path:'.local/drawing.png'});
console.log('loaded:',await page.locator('#stats').textContent(),await page.locator('#status').textContent());
await page.locator('[data-tab=texts]').click();
await page.locator('#search').fill('客厅');
console.log('text results',await page.locator('.row-label').count());
await page.locator('.row-label').first().click();
await page.screenshot({path:'.local/focus.png'});
console.log('selection',await page.locator('#selection-text').textContent());
const canvas=page.locator('#canvas');const b=await canvas.boundingBox();const start=await canvas.screenshot();
await page.mouse.move(b.x+b.width/2,b.y+b.height/2);await page.mouse.down();await page.mouse.move(b.x+b.width/2+120,b.y+b.height/2+90,{steps:10});await page.mouse.up();
await page.waitForTimeout(200);const moved=await canvas.screenshot();if(start.equals(moved))throw new Error('Pan did not change canvas');
const zoom=await page.locator('#zoom-label').textContent();await page.mouse.wheel(0,-350);await page.waitForTimeout(200);if(zoom===await page.locator('#zoom-label').textContent())throw new Error('Zoom did not change scale');
await page.locator('#spaces').selectOption('*Paper_Space');await page.waitForFunction(()=>document.querySelector('#loading').hidden);await page.screenshot({path:'.local/layout.png'});console.log('layout',await page.locator('#stats').textContent());
await page.locator('#file').setInputFiles({name:'invalid.dwg',mimeType:'application/octet-stream',buffer:Buffer.from('not a dwg')});await page.waitForFunction(()=>!document.querySelector('#toast').hidden);console.log('invalid',await page.locator('#toast').textContent());
fs.writeFileSync('.local/browser-result.json',JSON.stringify({errors,pan:true,zoom:true,layout:true,invalid:true},null,2));
await browser.close();if(errors.length)throw new Error(errors.join('\n'));
